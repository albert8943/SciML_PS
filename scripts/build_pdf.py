"""Build the SciML_PS full-book PDF (MyST → LaTeX → PDF).

Writes git commit metadata into ``templates/sciml_ps_book/gitinfo.tex``, runs
``jupyter-book build --pdf``, then (when MyST leaves a temp TeX tree) sanitizes
common text-mode math tokens, remaps ``framed`` callouts into branded
``tcolorbox`` environments, and recompiles with ``latexmk -xelatex``.

Copies the PDF to ``exports/sciml_ps_notes.pdf`` and into
``_build/html/exports/`` when an HTML tree exists.
"""

from __future__ import annotations

import re
import shutil
import subprocess
import sys
from datetime import datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
GITINFO = ROOT / "templates" / "sciml_ps_book" / "gitinfo.tex"
OUTPUT_PDF = ROOT / "exports" / "sciml_ps_notes.pdf"
PLACEHOLDER = (
    "% Written by scripts/build_pdf.py before each PDF build "
    "(placeholder for hand builds).\n"
    "% Cover shows Last updated from the latest git commit (local TZ + short hash).\n"
    "\\newcommand{\\lastcommitdate}{unknown (run scripts/build_pdf.py)}\n"
)

BEGIN_FRAMED = r"\begin{framed}"
END_FRAMED = r"\end{framed}"

TITLE_KIND = {
    "note": "mystnote",
    "tip": "mysttip",
    "warning": "mystwarning",
    "attention": "mystattention",
    "important": "mystattention",
    "seealso": "mystseealso",
    "hint": "mysttip",
    "caution": "mystwarning",
}

# MyST often emits these outside math; wrap for XeLaTeX text mode.
# Do not include short names like "to" (collides with \toprule, etc.).
MATH_MACROS = (
    "rightarrow",
    "leftarrow",
    "Rightarrow",
    "Leftarrow",
    "leftrightarrow",
    "Leftrightarrow",
    "mapsto",
)


def run(cmd: list[str], cwd: Path = ROOT, check: bool = True) -> subprocess.CompletedProcess[str]:
    print("$", " ".join(cmd))
    return subprocess.run(cmd, cwd=cwd, text=True, check=check)


def _utc_offset_label(dt: datetime) -> str:
    """Language-neutral zone label from the local offset, e.g. UTC+09:00 or UTC+05:30."""
    offset = dt.strftime("%z")  # +0900 / +0530
    if not offset or len(offset) < 5:
        return "local"
    return f"UTC{offset[:3]}:{offset[3:]}"


def format_local_timestamp(dt: datetime, *, weekday: bool = False) -> str:
    """Stamp times in the PDF builder's local timezone (Korea → UTC+09:00, India → UTC+05:30)."""
    local = dt.astimezone()  # convert to the machine's local zone
    hour = local.strftime("%I").lstrip("0") or "0"
    zone = _utc_offset_label(local)
    if weekday:
        return (
            f"{local:%A}, {local:%B} {local.day}, {local:%Y} "
            f"at {hour}:{local:%M} {local:%p} ({zone})"
        )
    return (
        f"{local:%B} {local.day}, {local:%Y} "
        f"at {hour}:{local:%M} {local:%p} ({zone})"
    )


def repo_last_commit() -> str:
    try:
        sha = subprocess.check_output(
            ["git", "log", "-1", "--format=%h"],
            cwd=ROOT,
            text=True,
        ).strip()
        iso = subprocess.check_output(
            ["git", "log", "-1", "--format=%cI"],
            cwd=ROOT,
            text=True,
        ).strip()
    except (subprocess.CalledProcessError, FileNotFoundError):
        return "unavailable"
    dt = datetime.fromisoformat(iso.replace("Z", "+00:00"))
    return f"{format_local_timestamp(dt)} ({sha})"


def _latex_escape(text: str) -> str:
    return (
        text.replace("\\", "\\textbackslash{}")
        .replace("&", "\\&")
        .replace("%", "\\%")
        .replace("#", "\\#")
        .replace("_", "\\_")
    )


def write_gitinfo(last_commit: str) -> None:
    """Write cover provenance: Last updated from latest git commit only (no build clock)."""
    GITINFO.parent.mkdir(parents=True, exist_ok=True)
    GITINFO.write_text(
        "% Auto-generated by scripts/build_pdf.py — do not edit by hand.\n"
        "% Cover \"Last updated\" = latest commit time (builder local TZ) + short hash.\n"
        f"\\newcommand{{\\lastcommitdate}}{{{_latex_escape(last_commit)}}}\n",
        encoding="utf-8",
    )


def classify_title(title: str) -> str:
    lowered = re.sub(r"\s+", " ", title.strip().lower())
    for key, env in TITLE_KIND.items():
        if lowered == key or lowered.startswith(key + " ") or lowered.startswith(key + ":"):
            return env
    if "activity" in lowered:
        return "mysttip"
    if "solution" in lowered:
        return "mystseealso"
    return "mystgeneric"


def transform_framed_blocks(text: str) -> str:
    def walk(start: int, stop_token: str | None = None) -> tuple[str, int]:
        pieces: list[str] = []
        idx = start
        while idx < len(text):
            if stop_token and text.startswith(stop_token, idx):
                return "".join(pieces), idx + len(stop_token)
            if text.startswith(BEGIN_FRAMED, idx):
                inner, idx = walk(idx + len(BEGIN_FRAMED), END_FRAMED)
                title_match = re.match(
                    r"\s*\\textbf\{([^{}]*)\}\s*(?:\\\\)?\s*",
                    inner,
                )
                if title_match:
                    title = title_match.group(1).strip() or "Note"
                    body = inner[title_match.end() :].lstrip("\n")
                else:
                    title = "Note"
                    body = inner.lstrip()
                env = classify_title(title)
                pieces.append(
                    f"\n\\begin{{{env}}}{{{title}}}\n{body.strip()}\n\\end{{{env}}}\n"
                )
                continue
            pieces.append(text[idx])
            idx += 1
        if stop_token:
            raise ValueError(f"Unclosed token {stop_token}")
        return "".join(pieces), idx

    try:
        return walk(0)[0]
    except ValueError:
        return text


def sanitize_math_macros(text: str) -> str:
    """Wrap bare math-only macros in text mode; leave macros inside $...$ alone."""
    out: list[str] = []
    i = 0
    in_math = False
    while i < len(text):
        ch = text[i]
        if ch == "$" and (i == 0 or text[i - 1] != "\\"):
            in_math = not in_math
            out.append(ch)
            i += 1
            continue
        if not in_math and ch == "\\":
            matched = False
            for name in MATH_MACROS:
                macro = "\\" + name
                if text.startswith(macro, i):
                    end = i + len(macro)
                    # MyST glues "→" to the next word ("stable\rightarrowunstable"); only
                    # \rightarrowtail-style names are genuinely longer macros.
                    if text.startswith("tail", end):
                        continue
                    out.append(f"${{{macro}}}$")
                    i = end
                    matched = True
                    break
            if matched:
                continue
        out.append(ch)
        i += 1
    return "".join(out)


def patch_tex_dir(build_dir: Path) -> bool:
    changed = False
    for tex_path in build_dir.glob("*.tex"):
        original = tex_path.read_text(encoding="utf-8", errors="replace")
        updated = sanitize_math_macros(original)
        if BEGIN_FRAMED in updated:
            updated = transform_framed_blocks(updated)
        if updated != original:
            tex_path.write_text(updated, encoding="utf-8")
            print("Patched", tex_path.name)
            changed = True
    return changed


def latest_myst_temp_dirs() -> list[Path]:
    temp = ROOT / "_build" / "temp"
    if not temp.is_dir():
        return []
    dirs = [p for p in temp.iterdir() if p.is_dir() and p.name.startswith("myst")]
    return sorted(dirs, key=lambda p: p.stat().st_mtime, reverse=True)


def recompile_temp_pdf(build_dir: Path) -> Path | None:
    main = build_dir / "sciml_ps_notes.tex"
    if not main.is_file():
        candidates = sorted(build_dir.glob("*.tex"), key=lambda p: p.stat().st_size, reverse=True)
        if not candidates:
            return None
        main = candidates[0]
    gitinfo_dest = build_dir / "gitinfo.tex"
    if not gitinfo_dest.is_file() and GITINFO.is_file():
        shutil.copy2(GITINFO, gitinfo_dest)
    if not shutil.which("latexmk"):
        print("latexmk not on PATH; skipping recompile", file=sys.stderr)
        return None
    result = run(
        [
            "latexmk",
            "-f",
            "-xelatex",
            "-interaction=batchmode",
            "-file-line-error",
            main.name,
        ],
        cwd=build_dir,
        check=False,
    )
    pdf = main.with_suffix(".pdf")
    if result.returncode != 0 and not pdf.is_file():
        print(f"latexmk failed in {build_dir} (exit {result.returncode})", file=sys.stderr)
        return None
    if pdf.is_file():
        print("Recompiled", pdf)
        return pdf
    return None


def build_pdf() -> None:
    if shutil.which("jupyter-book"):
        # MyST/JB may still exit 0 with LaTeX warnings; allow that.
        run(["jupyter-book", "build", "--pdf"], check=False)
    elif shutil.which("jupyter"):
        run(["jupyter", "book", "build", "--pdf"], check=False)
    elif shutil.which("myst"):
        run(["myst", "build", "--pdf"], check=False)
    else:
        raise FileNotFoundError(
            "Neither jupyter-book, jupyter, nor myst is on PATH. "
            "Run: conda activate sciml_ps"
        )


def polish_and_recompile() -> Path | None:
    """Sanitize TeX in the newest myst temp dirs and recompile when possible."""
    pdf: Path | None = None
    for build_dir in latest_myst_temp_dirs()[:3]:
        if not any(build_dir.glob("*.tex")):
            continue
        print("Polishing TeX in", build_dir)
        patch_tex_dir(build_dir)
        candidate = recompile_temp_pdf(build_dir)
        if candidate is not None:
            pdf = candidate
            break
    return pdf


def find_built_pdf() -> Path | None:
    if OUTPUT_PDF.is_file() and OUTPUT_PDF.stat().st_size > 0:
        return OUTPUT_PDF
    build = ROOT / "_build"
    if build.is_dir():
        named = list(build.rglob("sciml_ps_notes.pdf"))
        if named:
            return max(named, key=lambda p: p.stat().st_mtime)
        pdfs = sorted(build.rglob("*.pdf"), key=lambda p: p.stat().st_mtime, reverse=True)
        if pdfs:
            return pdfs[0]
    return None


def sync_pdf_into_site(pdf: Path | None = None) -> list[Path]:
    """Copy the notes PDF into live site trees so /exports/sciml_ps_notes.pdf works.

    Jupyter Book 2 preview serves from ``_build/site/public``. Without this sync,
    the navbar PDF URL 404s or points at a stale hashed copy under ``public/``.
    """
    src = pdf or OUTPUT_PDF
    if not src.is_file() or src.stat().st_size == 0:
        return []
    targets: list[Path] = []
    site_public = ROOT / "_build" / "site" / "public"
    if site_public.is_dir():
        targets.append(site_public / "exports" / src.name)
    html_root = ROOT / "_build" / "html"
    if html_root.is_dir():
        targets.append(html_root / "exports" / src.name)
    copied: list[Path] = []
    for dest in targets:
        dest.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(src, dest)
        copied.append(dest)
        print("Synced PDF for site:", dest)
    return copied


def main(argv: list[str] | None = None) -> int:
    args = list(sys.argv[1:] if argv is None else argv)
    if args and args[0] == "--sync-only":
        copied = sync_pdf_into_site()
        if not copied:
            if not OUTPUT_PDF.is_file():
                print(
                    f"No PDF at {OUTPUT_PDF}. Run scripts/build_pdf.py first.",
                    file=sys.stderr,
                )
                return 1
            print(
                "PDF exists but no _build/site/public or _build/html tree yet; "
                "start preview or build the site, then re-run --sync-only.",
                file=sys.stderr,
            )
            return 1
        return 0

    last = repo_last_commit()
    print("Last repo commit:", last)
    write_gitinfo(last)
    try:
        build_pdf()
        polished = polish_and_recompile()
        pdf = polished or find_built_pdf()
    except FileNotFoundError as exc:
        print(str(exc), file=sys.stderr)
        return 1
    except subprocess.CalledProcessError as exc:
        print(f"PDF build failed with exit code {exc.returncode}", file=sys.stderr)
        return exc.returncode
    finally:
        GITINFO.write_text(PLACEHOLDER, encoding="utf-8")

    if pdf is None or not pdf.is_file():
        print("PDF build finished but no PDF file was found.", file=sys.stderr)
        return 1

    OUTPUT_PDF.parent.mkdir(parents=True, exist_ok=True)
    if pdf.resolve() != OUTPUT_PDF.resolve():
        shutil.copy2(pdf, OUTPUT_PDF)
    print("Wrote", OUTPUT_PDF)
    sync_pdf_into_site(OUTPUT_PDF)
    return 0


if __name__ == "__main__":
    sys.exit(main())
